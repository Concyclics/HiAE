int functional_test_work(size_t plain_len, size_t ad_len)
{
    uint8_t key[32];
    uint8_t iv[16];

    uint8_t *ad = (uint8_t *)malloc(ad_len);
    uint8_t *plain = (uint8_t *)malloc(plain_len);
    uint8_t *cipher = (uint8_t *)malloc(plain_len);
    uint8_t *decode = (uint8_t *)malloc(plain_len);

    for (int i = 0; i < 32; i++)
        key[i] = rand() % 256;
    for (int i = 0; i < 16; i++)
        iv[i] = rand() % 256;
    for (size_t i = 0; i < plain_len; i++)
        plain[i] = rand() % 256;
    for (size_t i = 0; i < ad_len; i++)
        ad[i] = rand() % 256;

    uint8_t tag1[16], tag2[16];

    DATA128b state[STATE];

    int rnd_0, rnd_1, rnd_2, rnd_3;
    rnd_0 = rand() % ad_len;
    rnd_1 = rand() % plain_len;
    rnd_2 = rand() % plain_len;
    rnd_3 = rand() % ad_len;
    rnd_0 -= rnd_0 % 16;
    rnd_1 -= rnd_1 % 16;
    rnd_2 -= rnd_2 % 16;
    rnd_3 -= rnd_3 % 16;

    HiAE_stream_init(state, key, iv);
    HiAE_stream_proc_ad(state, ad, rnd_0);
    HiAE_stream_proc_ad(state, ad + rnd_0, (ad_len - rnd_0));
    HiAE_stream_encrypt(state, cipher, plain, rnd_1);
    HiAE_stream_encrypt(state, cipher + rnd_1, plain + rnd_1, (plain_len - rnd_1));
    HiAE_stream_finalize(state, ad_len, plain_len, tag1);

    HiAE_stream_init(state, key, iv);
    HiAE_stream_proc_ad(state, ad, rnd_3);
    HiAE_stream_proc_ad(state, ad + rnd_3, (ad_len - rnd_3));
    HiAE_stream_decrypt(state, decode, cipher, rnd_2);
    HiAE_stream_decrypt(state, decode + rnd_2, cipher + rnd_2, (plain_len - rnd_2));
    HiAE_stream_finalize(state, ad_len, plain_len, tag2);

    int same_msg = memcmp(plain, decode, plain_len);
    int same_tag = memcmp(tag1, tag2, 16);
    free(ad);
    free(plain);
    free(cipher);
    free(decode);

    if (!(same_msg | same_tag))
    {
        return 1;
    }
    else
    {
        return 0;
    }

    return 0;
}

void functional_test()
{
    int result = 0;
    srand(time(NULL));
    int size_group = 4;
    double avg_ad = 0, avg_len = 0;
    int max_len = 0, min_len = 1 << 30, max_ad = 0, min_ad = 1 << 30;
    int size_L[5] = {1, 256, 1024, 8192, 16384};
    for (int i = 0; i < size_group; i++)
    {

        int T = REPEAT;
        while (T--)
        {
            int len = rand() % (size_L[i + 1] - size_L[i] + 1) + size_L[i];
            int ad_len = rand() % (size_L[i + 1] - size_L[i] + 1) + size_L[i];
            result += functional_test_work(len, ad_len);
            avg_ad += ad_len;
            avg_len += len;
            max_len = MAX(max_len, len);
            min_len = MIN(min_len, len);
            max_ad = MAX(max_ad, ad_len);
            min_ad = MIN(min_ad, ad_len);
        }
    }
    if (result == REPEAT * size_group)
    {
        printf("functional test pass.  \t");
    }
    else
    {
        printf("functional test failed!  \t");
    }
    printf("passed: %d of total %d test cases.\n", result, REPEAT * size_group);
    printf("average AD len: %.2f Bytes \t average message len: %.2f Bytes\n", avg_ad / REPEAT / size_group, avg_len / REPEAT / size_group);
}

